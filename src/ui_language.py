"""Translate interface labels independently of production rules and project data."""

import os
from pathlib import Path

from .production_project import atomic_text


def preference_path():
    app_data = os.environ.get("LOCALAPPDATA")
    return Path(app_data) / "ComicFlow" / "ui-language.txt" if app_data else None


def load_language():
    path = preference_path()
    if path is not None:
        try:
            language = path.read_text(encoding="utf-8").strip()
            if language in {"zh", "en"}:
                return language
        except (OSError, UnicodeError):
            pass
    return "zh"


def save_language(language):
    path = preference_path()
    if path is not None:
        path.parent.mkdir(parents=True, exist_ok=True)
        atomic_text(path, language + "\n")


def translate(widget, text):
    if getattr(widget._root(), "ui_language", "zh") == "en":
        return ENGLISH.get(text, text)
    return text


